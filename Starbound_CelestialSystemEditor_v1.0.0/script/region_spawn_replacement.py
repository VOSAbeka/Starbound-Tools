"""Inspect/replace compiled spawn profiles in a world-layout rectangle.

Only layout block-biome references are redirected. Engine evidence:
source/game/StarWorldGeneration.cpp:631-642 explicitly uses the BLOCK biome
for getSpawnProfile, not the environment biome or saved tile biome bytes.
The original biome's other fields and each cell's selectors remain unchanged.

These are exact *layout* rectangles, not hard fences for monster positions:
StarWorldTemplate.cpp:633-664 applies native biome noise/blending, and
StarSpawner.cpp:272-305 samples spawn-cell centres before adjusting positions.
Adding layout boundaries also redistributes native region weights. Although
non-spawn fields are unchanged, effective edge environment/liquid selection and
future terrain blending can change, including just outside the rectangle. No
existing saved terrain is regenerated by this operation.
This module does no filesystem I/O, sector reset, or saved-tile mutation.
"""

from __future__ import annotations

import copy
import json
import math
from collections.abc import Iterable
from pathlib import Path
from typing import Any

if __package__:
    from .biome_index_safety import MAX_BIOME_INDEX, BiomeIndexCapacityError, _biome_identity
else:
    from biome_index_safety import MAX_BIOME_INDEX, BiomeIndexCapacityError, _biome_identity


def _strict_json(value: Any, path: str = "spawnProfile") -> None:
    if value is None or type(value) in (bool, int, str):
        return
    if type(value) is float:
        if not math.isfinite(value):
            raise ValueError(f"{path} must not contain NaN or Infinity")
        return
    if isinstance(value, list):
        for index, child in enumerate(value):
            _strict_json(child, f"{path}[{index}]")
        return
    if isinstance(value, dict):
        for key, child in value.items():
            if type(key) is not str:
                raise ValueError(f"{path} object keys must be strings")
            _strict_json(child, f"{path}.{key}")
        return
    raise ValueError(f"{path} contains a non-JSON value: {type(value).__name__}")


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON object key: {key}")
        result[key] = value
    return result


def normalize_spawn_profile(
    value: Any, *, known_spawn_types: Iterable[str] | None = None
) -> dict[str, Any] | None:
    """Accept raw/wrapped JSON or a ``\"spawnProfile\": {...}`` fragment.

    None/whitespace means do nothing, while an explicit empty spawnTypes list
    clears the pool. Nonempty input replaces the WHOLE profile. Missing shared
    monsterParameters becomes {}, never inherits previous parameters; explicit
    null remains null (native StarSpawnTypeDatabase.cpp:80-92 accepts it).
    Compiled spawnTypes are names, not weighted/object entries. Duplicates are
    removed in first-seen order, matching native StringSet semantics.

    Optional known_spawn_types checks resolved .spawntypes names. Without it,
    resource existence is not checked. Known native monster parameter scalar
    types are always checked; unknown extension keys are preserved.
    """
    if value is None:
        return None
    if isinstance(value, str):
        text = value.lstrip("\ufeff").strip()
        if not text:
            return None
        if text.startswith('"spawnProfile"'):
            text = "{" + (text[:-1].rstrip() if text.endswith(",") else text) + "}"
        try:
            value = json.loads(text, object_pairs_hook=_unique_object)
        except (json.JSONDecodeError, ValueError) as exc:
            raise ValueError(f"Invalid spawnProfile JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError("Spawn profile must be a JSON object")
    if "spawnProfile" in value:
        value = value["spawnProfile"]
    if not isinstance(value, dict):
        raise ValueError("spawnProfile must contain a JSON object")
    _strict_json(value)
    names = value.get("spawnTypes")
    if not isinstance(names, list):
        raise ValueError("spawnProfile.spawnTypes must be an array of spawn-type names")
    if any(type(name) is not str or not name or name != name.strip() for name in names):
        raise ValueError("spawnTypes entries must be non-empty names without surrounding whitespace")
    parameters = value.get("monsterParameters", {})
    if parameters is not None and not isinstance(parameters, dict):
        raise ValueError("spawnProfile.monsterParameters must be an object or null")
    # Also guard callers outside the GUI. This import is intentionally local:
    # the read-only resource validator reuses this structural normalizer.
    if __package__:
        from .celestial_resource_validation import validate_monster_parameters
    else:
        from celestial_resource_validation import validate_monster_parameters
    validate_monster_parameters(parameters, label="spawnProfile.monsterParameters")
    unique_names = list(dict.fromkeys(names))
    if known_spawn_types is not None:
        if isinstance(known_spawn_types, (str, bytes)):
            raise ValueError("known_spawn_types must be a collection of spawn-type names")
        known = set(known_spawn_types)
        if any(type(name) is not str or not name for name in known):
            raise ValueError("known_spawn_types must contain non-empty strings")
        unknown = [name for name in unique_names if name not in known]
        if unknown:
            raise ValueError("Unknown spawnTypes: " + ", ".join(unknown))
    result = copy.deepcopy(value)
    result["spawnTypes"] = unique_names
    result["monsterParameters"] = copy.deepcopy(parameters)
    return result


def normalize_spawn_profile_template(
    value: Any, *, known_spawn_types: Iterable[str] | None = None
) -> dict[str, Any] | None:
    """Validate the GUI's explicit ``spawnProfile`` input template.

    The displayed fragment ``"spawnProfile": {...}`` and the equivalent full
    outer JSON object are accepted.  A raw inner profile is rejected so a user
    cannot accidentally mistake one field for an append operation.  Native
    SpawnProfile has exactly monsterParameters and spawnTypes; both are
    required here and extra keys fail closed.
    """
    if value is None:
        return None
    if isinstance(value, str):
        text = value.lstrip("\ufeff").strip()
        if not text:
            return None
        if text.startswith('"spawnProfile"'):
            text = "{" + (text[:-1].rstrip() if text.endswith(",") else text) + "}"
        try:
            wrapper = json.loads(text, object_pairs_hook=_unique_object)
        except (json.JSONDecodeError, ValueError) as exc:
            raise ValueError(f"Invalid spawnProfile JSON: {exc}") from exc
    else:
        wrapper = copy.deepcopy(value)
    if not isinstance(wrapper, dict) or set(wrapper) != {"spawnProfile"}:
        raise ValueError(
            'Use the displayed template: "spawnProfile": { '
            '"monsterParameters": {...}, "spawnTypes": [...] }'
        )
    profile = wrapper["spawnProfile"]
    if not isinstance(profile, dict) or set(profile) != {"monsterParameters", "spawnTypes"}:
        raise ValueError(
            "spawnProfile must contain exactly monsterParameters and spawnTypes, "
            "as shown in the template"
        )
    if not isinstance(profile["monsterParameters"], dict):
        raise ValueError(
            "spawnProfile.monsterParameters must be a JSON object in this input template"
        )
    return normalize_spawn_profile(
        wrapper, known_spawn_types=known_spawn_types
    )


def load_spawn_type_names(
    assets: Path, *, asset_sources: Iterable[Path] | None = None
) -> set[str]:
    """Load compiled spawn names from an explicitly resolved asset stack.

    ``asset_sources`` is low-to-high priority, including any actual-game mod
    folders/paks chosen by the caller. Omitting it discovers this installation's
    sources; it does not silently import another installation's workshop mods.
    Source overlays and .patch files share dungeon_choices' strict resolver:
    unsupported/failed patches raise rather than claiming a complete catalog.
    The engine scans every .spawntypes array's entries and takes each ``name``,
    not ``monsterType`` (StarSpawnTypeDatabase.cpp:53-54,112-143).
    """
    from dungeon_choices import AssetCatalogError, AssetSourceStack, discover_asset_sources

    sources = list(asset_sources) if asset_sources is not None else discover_asset_sources(Path(assets))
    if not sources:
        raise ValueError("No asset sources are available to validate spawnTypes")
    stack = AssetSourceStack(sources)
    names = set()
    for path in stack.paths(".spawntypes"):
        definitions = stack.json(path)
        if not isinstance(definitions, list):
            raise AssetCatalogError(f"Spawn type asset {path} must contain an array")
        for definition in definitions:
            if not isinstance(definition, dict):
                raise AssetCatalogError(f"Spawn type entries in {path} must contain objects")
            name = definition.get("name")
            if not isinstance(name, str) or not name or name != name.strip():
                raise AssetCatalogError(f"Spawn type asset {path} contains an invalid name {name!r}")
            if name in names:
                raise AssetCatalogError(f"Duplicate spawn type named {name} in {path}")
            names.add(name)
    return names


def _layout(
    document: dict[str, Any], x_start: int, x_end: int, y_start: int, y_end: int
) -> tuple[dict[str, Any], list[dict[str, Any]], list[dict[str, Any]], int, int, list[tuple[int, int]]]:
    if not isinstance(document, dict):
        raise ValueError("World document must be an object")
    size = document.get("size")
    if (not isinstance(size, (list, tuple)) or len(size) != 2
            or any(type(number) is not int or number <= 0 for number in size)):
        raise ValueError("World size must contain two positive integers")
    width, height = size
    if any(type(number) is not int for number in (x_start, x_end, y_start, y_end)):
        raise ValueError("Rectangle coordinates must be integers after sector rounding")
    if not 0 <= x_start < width or not 0 <= x_end < width:
        raise ValueError(f"X coordinates must be in 0..{width - 1}")
    if not 0 <= y_start <= y_end < height:
        raise ValueError(f"Y coordinates must increase within 0..{height - 1}")
    metadata = document.get("metadata")
    template = metadata.get("worldTemplate") if isinstance(metadata, dict) else None
    region = template.get("regionData") if isinstance(template, dict) else None
    if not isinstance(region, dict):
        raise ValueError("worldTemplate.regionData is missing")
    biomes, layers = region.get("biomes"), region.get("layers")
    if not isinstance(biomes, list) or any(not isinstance(biome, dict) for biome in biomes):
        raise ValueError("Compiled biomes must be an array of objects")
    if not isinstance(layers, list) or not layers:
        raise ValueError("Compiled world layers are missing or empty")
    starts = []
    for layer in layers:
        start = layer.get("yStart") if isinstance(layer, dict) else None
        if type(start) is not int or not 0 <= start < height:
            raise ValueError(f"Invalid layer yStart: {start!r}")
        starts.append(start)
    if starts[0] != 0 or any(left >= right for left, right in zip(starts, starts[1:])):
        raise ValueError("Layer yStart values must increase uniquely from zero")
    x_ranges = [(x_start, x_end)] if x_start <= x_end else [(x_start, width - 1), (0, x_end)]
    return region, biomes, layers, width, height, x_ranges


def _cell_ranges(layer: dict[str, Any], width: int):
    boundaries, cells = layer.get("boundaries"), layer.get("cells")
    if not isinstance(boundaries, list) or not isinstance(cells, list):
        raise ValueError("Compiled world layer has invalid boundaries/cells")
    if len(cells) != len(boundaries) + 1:
        raise ValueError("Compiled world layer cell count does not match boundaries")
    if any(type(boundary) is not int for boundary in boundaries):
        raise ValueError("Compiled world layer boundaries must be integers")
    edges = [0] + [boundary + 1 for boundary in boundaries] + [width]
    if any(left >= stop for left, stop in zip(edges, edges[1:])):
        raise ValueError("Compiled world layer boundaries must increase within world width")
    for cell, left, stop in zip(cells, edges, edges[1:]):
        if not isinstance(cell, dict):
            raise ValueError("Compiled world layer cells must be objects")
        yield cell, left, stop - 1


def _selected_cells(layers, width, height, x_ranges, y_start, y_end, biome_count):
    for position, layer in enumerate(layers):
        bottom = layer["yStart"]
        top = layers[position + 1]["yStart"] - 1 if position + 1 < len(layers) else height - 1
        if bottom > y_end or top < y_start:
            continue
        for cell, left, right in _cell_ranges(layer, width):
            intersections = [(max(left, start), min(right, end)) for start, end in x_ranges
                             if left <= end and start <= right]
            if not intersections:
                continue
            index = cell.get("blockBiomeIndex")
            if type(index) is not int or not 0 <= index <= biome_count:
                raise ValueError(
                    f"Selected spawn region has invalid blockBiomeIndex {index!r}; "
                    f"expected 0..{biome_count} at X {left}..{right}, Y {bottom}"
                )
            for start, end in intersections:
                yield index, position, {
                    "xStart": start, "xEnd": end,
                    "yStart": max(bottom, y_start), "yEnd": min(top, y_end),
                }


def inspect_spawn_rectangle(
    document: dict[str, Any], x_start: int, x_end: int, y_start: int, y_end: int
) -> dict[str, Any]:
    """Read selected block-biome pools grouped by biome name and monster names.

    monsterParameters are deliberately excluded. Same-name biome variants with
    different spawn pools remain separate groups; indexes/ranges retain origin.
    Returned lists are independent copies and never expose mutable world data.
    """
    _region, biomes, layers, width, height, x_ranges = _layout(
        document, x_start, x_end, y_start, y_end
    )
    groups: dict[tuple[str, tuple[str, ...]], dict[str, Any]] = {}
    for index, _position, rectangle in _selected_cells(
        layers, width, height, x_ranges, y_start, y_end, len(biomes)
    ):
        biome = biomes[index - 1] if index else {}
        name = biome.get("baseName", "")
        if not isinstance(name, str):
            raise ValueError(f"Biome {index} has an invalid baseName")
        profile = biome.get("spawnProfile")
        if profile is not None and not isinstance(profile, dict):
            raise ValueError(f"Biome {index} spawnProfile must be an object or null")
        names = profile.get("spawnTypes", []) if profile is not None else []
        if not isinstance(names, list) or any(type(item) is not str or not item for item in names):
            raise ValueError(f"Biome {index} spawnTypes must be an array of names")
        # Native StringSet order is not semantic; this also groups reordered pools.
        unique_names = sorted(set(names))
        key = name, tuple(unique_names)
        group = groups.setdefault(key, {
            "biomeName": name, "biomeIndexes": [], "spawnTypes": unique_names,
            "ranges": [], "tileCount": 0,
        })
        if index not in group["biomeIndexes"]:
            group["biomeIndexes"].append(index)
        group["ranges"].append(rectangle)
        group["tileCount"] += (rectangle["xEnd"] - rectangle["xStart"] + 1) * (
            rectangle["yEnd"] - rectangle["yStart"] + 1
        )
    for group in groups.values():
        group["biomeIndexes"].sort()
    return {
        "source": "blockBiomeIndex", "xRanges": [list(pair) for pair in x_ranges],
        "yStart": y_start, "yEnd": y_end, "groups": list(groups.values()),
    }


def _empty_spawn_biome() -> dict[str, Any]:
    # Native Biome defaults/required disk keys: StarBiome.cpp:8-20,43-72.
    # 65535 is EmptyMaterialId/NoModId (StarMaterialTypes.hpp:9,48).
    placeables = {
        "grassMod": 65535, "grassModDensity": 0.0,
        "ceilingGrassMod": 65535, "ceilingGrassModDensity": 0.0,
        "itemDistributions": [],
    }
    return {
        "baseName": "", "description": "", "mainBlock": 65535,
        "subBlocks": [], "ores": [], "hueShift": 0.0, "materialHueShift": 0,
        "surfacePlaceables": copy.deepcopy(placeables),
        "undergroundPlaceables": copy.deepcopy(placeables),
        "spawnProfile": {"spawnTypes": [], "monsterParameters": None},
        "ambientNoises": None, "musicTrack": None,
    }


def _profile_identity(profile: Any) -> str | None:
    """Only spawnTypes order/duplicates are non-semantic native StringSet data."""
    if not isinstance(profile, dict):
        return None
    names = profile.get("spawnTypes")
    if not isinstance(names, list) or any(type(name) is not str for name in names):
        return None
    candidate = copy.deepcopy(profile)
    candidate["spawnTypes"] = sorted(set(names))
    return _biome_identity(candidate)


def _overlay_blocks(layer, width, x_ranges, mapping):
    old_boundary_count = len(layer["boundaries"])
    cells, ends = [], []
    for cell, left, right in _cell_ranges(layer, width):
        old = cell.get("blockBiomeIndex")
        cuts = {left, right + 1}
        if type(old) is int and old in mapping and mapping[old] != old:
            for start, end in x_ranges:
                if left <= end and start <= right:
                    cuts.update((max(left, start), min(right, end) + 1))
        edges = sorted(cuts)
        for start, stop in zip(edges, edges[1:]):
            candidate = copy.deepcopy(cell)
            if any(begin <= start <= end for begin, end in x_ranges):
                candidate["blockBiomeIndex"] = mapping[old]
            cells.append(candidate)
            ends.append(stop - 1)
    layer["cells"], layer["boundaries"] = cells, ends[:-1]
    return len(layer["boundaries"]) - old_boundary_count


def _check_capacity(biomes: list[dict[str, Any]]) -> None:
    if len(biomes) <= MAX_BIOME_INDEX:
        return
    identities = set()
    non_finite_count = 0
    for biome in biomes:
        identity = _biome_identity(biome)
        if identity is None:
            non_finite_count += 1
        else:
            identities.add(identity)
    count = len(identities) + non_finite_count
    if count > MAX_BIOME_INDEX:
        raise BiomeIndexCapacityError(
            f"Spawn replacement needs {count} distinct or non-finite compiled biomes; "
            f"native indexes allow at most {MAX_BIOME_INDEX}. No world data was changed."
        )


def set_spawn_profile_rectangle(
    document: dict[str, Any], x_start: int, x_end: int, y_start: int, y_end: int,
    profile: Any, *, known_spawn_types: Iterable[str] | None = None,
) -> dict[str, Any]:
    """Stage and atomically replace selected layout block-biome spawn profiles.

    Existing compiled definitions are not edited. Full-field identical target
    definitions are reused; otherwise one clone per distinct source is appended.
    Temporary indexes >255 require the caller's existing whole-world duplicate
    compaction (including BOTH saved tile bytes) before serialization. If exact
    compaction cannot fit, this fails without modifying the document. This
    module cannot safely compact alone because it does not own world records.
    """
    normalized = normalize_spawn_profile(profile, known_spawn_types=known_spawn_types)
    report = {
        "spawnOnly": True, "changed": False, "changedLayers": 0,
        "sourceBlockBiomeIndexes": [], "targetBlockBiomeIndexes": [],
        "biomeIndexMapping": {}, "newBiomeCount": 0, "requiresBiomeCompaction": False,
        "layoutTopologyChanged": False, "addedLayerBoundaries": 0, "addedCellBoundaries": 0,
    }
    if normalized is None:
        return report
    region, biomes, layers, width, height, x_ranges = _layout(
        document, x_start, x_end, y_start, y_end
    )
    selected = list(_selected_cells(layers, width, height, x_ranges, y_start, y_end, len(biomes)))
    sources = sorted({index for index, _position, _rectangle in selected})
    identities = {}
    for index, biome in enumerate(biomes, 1):
        identity = _biome_identity(biome)
        if identity is not None:
            identities.setdefault(identity, index)
    mapping, clones = {}, []
    profile_identity = _profile_identity(normalized)
    for source in sources:
        original = biomes[source - 1] if source else _empty_spawn_biome()
        old_profile = original.get("spawnProfile")
        if _profile_identity(old_profile) == profile_identity:
            mapping[source] = source
            continue
        candidate = copy.deepcopy(original)
        candidate["spawnProfile"] = copy.deepcopy(normalized)
        identity = _biome_identity(candidate)
        target = identities.get(identity) if identity is not None else None
        if target is None:
            clones.append(candidate)
            target = len(biomes) + len(clones)
            if identity is not None:
                identities[identity] = target
        mapping[source] = target
    _check_capacity(biomes + clones)
    changed_positions = {position for index, position, _rectangle in selected if mapping[index] != index}
    staged_layers = []
    for position, original in enumerate(layers):
        bottom = original["yStart"]
        stop = layers[position + 1]["yStart"] if position + 1 < len(layers) else height
        if position not in changed_positions:
            staged_layers.append(copy.deepcopy(original))
            continue
        cuts = sorted({bottom, stop} | {edge for edge in (y_start, y_end + 1) if bottom < edge < stop})
        for start, _end in zip(cuts, cuts[1:]):
            layer = copy.deepcopy(original)
            layer["yStart"] = start
            if y_start <= start <= y_end:
                report["addedCellBoundaries"] += _overlay_blocks(layer, width, x_ranges, mapping)
                report["changedLayers"] += 1
            staged_layers.append(layer)
    report["addedLayerBoundaries"] = len(staged_layers) - len(layers)
    report["layoutTopologyChanged"] = bool(report["addedLayerBoundaries"] or report["addedCellBoundaries"])
    report.update({
        "changed": bool(changed_positions), "sourceBlockBiomeIndexes": sources,
        "targetBlockBiomeIndexes": sorted(set(mapping.values())),
        "biomeIndexMapping": mapping, "newBiomeCount": len(clones),
        "requiresBiomeCompaction": len(biomes) + len(clones) > MAX_BIOME_INDEX,
    })
    if report["changed"]:
        # Commit after every profile, selected index, geometry and capacity check.
        region["biomes"] = biomes + clones
        region["layers"] = staged_layers
    return report
